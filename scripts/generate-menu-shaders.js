/* global __dirname */
// Generates modules/.../menu-trigger/menu-shaders.web.ts from render/GlassShaders.kt.
// The AGSL sources are raw strings joined with `+`; this evaluates those joins in the same order,
// so the SkSL the web uses is byte-identical to the Kotlin string.
//
//   node scripts/generate-menu-shaders.js          write the file
//   node scripts/generate-menu-shaders.js --check  fail if the file is out of date
const fs = require("fs");
const path = require("path");

const root = path.resolve(__dirname, "..");
const ktPath = path.join(
  root,
  "modules/glass-menu-android/android/src/main/java/expo/modules/glassmenuandroid/render/GlassShaders.kt",
);
const outPath = path.join(root, "modules/glass-menu-android/src/components/menu-trigger/menu-shaders.web.ts");

const text = fs.readFileSync(ktPath, "utf8");
const declRe = /^(?:private |internal )?const val (\w+) = /gm;
const decls = [];
let m;
while ((m = declRe.exec(text))) decls.push({ name: m[1], declAt: m.index, start: m.index + m[0].length });
const env = {};
decls.forEach((decl, i) => {
  // The expression runs from `start` to the next declaration (or the end of the file).
  const end = i + 1 < decls.length ? decls[i + 1].declAt : text.length;
  const expr = text.slice(decl.start, end);
  const parts = [];
  const tokRe = /"""([\s\S]*?)"""|\b([A-Za-z_]\w*)\b/g;
  let t;
  while ((t = tokRe.exec(expr))) {
    if (t[1] !== undefined) parts.push(t[1]);
    else if (t[2] in env) parts.push(env[t[2]]);
    else throw new Error(`${decl.name}: unresolved reference ${t[2]}`);
  }
  env[decl.name] = parts.join("");
});

const names = ["GlassMaterialShader", "GlassPortalShader", "GlassShadowShader"];
const lines = [
  "// Generated by scripts/generate-menu-shaders.js from render/GlassShaders.kt. Do not edit.",
  "// These are the AGSL sources from Kotlin, evaluated to the same string, used as SkSL via",
  "// RuntimeEffect.Make. Syntax differences (if any) are listed in scripts/generate-menu-shaders.js.",
  "",
];
for (const name of names) {
  if (!(name in env)) throw new Error(`missing ${name}`);
  lines.push(`export const ${name.replace(/^Glass/, "GLASS_").replace(/([a-z])([A-Z])/g, "$1_$2").toUpperCase()}_SKSL = ${JSON.stringify(env[name])};`);
  lines.push("");
}
const output = lines.join("\n");

if (process.argv.includes("--check")) {
  const current = fs.existsSync(outPath) ? fs.readFileSync(outPath, "utf8") : "";
  if (current !== output) {
    console.error("menu-shaders.web.ts is out of date: run node scripts/generate-menu-shaders.js");
    process.exit(1);
  }
  console.log("SHADERS UP TO DATE");
} else {
  fs.writeFileSync(outPath, output);
  console.log(`wrote ${path.relative(root, outPath)} (${names.map((n) => `${n}: ${env[n].length} chars`).join(", ")})`);
}
